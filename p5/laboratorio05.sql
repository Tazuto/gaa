CREATE DATABASE IF NOT EXISTS laboratorio05
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE laboratorio05;

CREATE TABLE IF NOT EXISTS registros_academicos (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    codigo VARCHAR(10) NOT NULL UNIQUE,
    nombres VARCHAR(120) NOT NULL,
    correo VARCHAR(120) NOT NULL,
    fecha_nacimiento DATE NOT NULL,
    escuela VARCHAR(100) NOT NULL,
    ciclo TINYINT UNSIGNED NOT NULL,
    modalidad VARCHAR(30) NOT NULL,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS contactos (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    email VARCHAR(120) NOT NULL,
    telefono VARCHAR(20) NOT NULL,
    comentario TEXT NOT NULL,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS preferencias (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    participante VARCHAR(120) NOT NULL,
    tema VARCHAR(80) NOT NULL,
    herramientas TEXT NOT NULL,
    intereses TEXT NOT NULL,
    lenguaje VARCHAR(60) NOT NULL,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS equipos (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS integrantes (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    equipo_id INT UNSIGNED NOT NULL,
    nombre VARCHAR(120) NOT NULL,
    CONSTRAINT fk_integrantes_equipo
        FOREIGN KEY (equipo_id) REFERENCES equipos(id)
        ON DELETE CASCADE
);